// Shuffle function for variety
function shuffleArray(array) {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

// Get random questions, biased toward user's interests
function getQuickQuestions(userContext = {}, count = 3) {
  const questions = shuffleArray(QUICK_QUESTIONS);
  
  // If we know user's interests, try to pick relevant ones
  if (userContext.topics && userContext.topics.length > 0) {
    const relevant = questions.filter(q => {
      const lower = q.toLowerCase();
      return userContext.topics.some(t => lower.includes(t.toLowerCase()));
    });
    if (relevant.length >= count) {
      return relevant.slice(0, count);
    }
  }
  
  // Default: return first 3 random questions
  return questions.slice(0, count);
}

