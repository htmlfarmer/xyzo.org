"""Publish the daily digest video to YouTube.

INERT BY DEFAULT. Uploading needs a YouTube OAuth refresh token for the
target channel, which is a credential and therefore never lives in the
repo — it goes in the env file (/etc/xyzo/xyzo.env) or the process
environment:

    YOUTUBE_CLIENT_ID=...
    YOUTUBE_CLIENT_SECRET=...
    YOUTUBE_REFRESH_TOKEN=...
    YOUTUBE_CHANNEL_ID=...        # optional, for the description

Without those this script refuses to do anything and says so — it will
never half-upload.

To get a refresh token (once, by hand):
    python3 -m worker.digest_upload --auth
which prints an authorisation URL, asks for the code, and exchanges it for a
refresh token. The token is then stored in the env file for you to paste.

Usage:
    python3 -m worker.digest_upload --status      # what would be published
    python3 -m worker.digest_upload --dry-run     # build metadata, no upload
    python3 -m worker.digest_upload               # upload for real
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone
from typing import Any, Optional

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_VIDEO = os.path.join(REPO, "data", "digest_video", "xyzo-daily.mp4")
DEFAULT_STORYBOARD = os.path.join(REPO, "data", "digest_video", "storyboard.json")
DEFAULT_DIGEST = os.path.join(REPO, "data", "daily_digest.json")

# YouTube's API costs 1600 units for a video insert; the default daily
# quota is 10,000 units, so ~6 uploads/day. We upload once.
SCOPES = ["https://www.googleapis.com/auth/youtube.upload"]


def _log(msg: str) -> None:
    print(f"[upload] {msg}", flush=True)


def load_credentials() -> dict[str, str]:
    """Read the YouTube credentials from the environment.

    The env file is loaded by the systemd units; for a manual run the
    caller can `set -a; . /etc/xyzo/xyzo.env; set +a` first.
    """
    return {
        "client_id": os.environ.get("YOUTUBE_CLIENT_ID", ""),
        "client_secret": os.environ.get("YOUTUBE_CLIENT_SECRET", ""),
        "refresh_token": os.environ.get("YOUTUBE_REFRESH_TOKEN", ""),
        "channel_id": os.environ.get("YOUTUBE_CHANNEL_ID", ""),
    }


def credentials_present(creds: dict[str, str]) -> list[str]:
    return [k for k in ("client_id", "client_secret", "refresh_token") if not creds.get(k)]


def build_metadata(digest: dict, storyboard: dict) -> dict[str, Any]:
    """Title, description and tags for the video.

    YouTube asks creators to disclose realistic synthetic content — the
    narration is machine-generated, so the description says so.
    """
    stories = digest.get("stories", [])
    when = digest.get("generated_at", "")[:10]

    title_bits = ["XYZO Daily"]
    if stories:
        title_bits.append(stories[0].get("headline_en") or stories[0].get("headline") or "")
    title = " — ".join(b for b in title_bits if b)[:100]

    lines = [
        f"XYZO Daily — {when}",
        "",
        "The day's most interesting stories, mapped. Curated from "
        f"{sum(int(s.get('articles') or 0) for s in stories):,} articles across "
        f"{len({s.get('country') for s in stories if s.get('country')})} countries.",
        "",
        "Today's stories:",
    ]
    for s in stories:
        head = s.get("headline_en") or s.get("headline") or ""
        where = ", ".join(p for p in [s.get("place"), s.get("country")] if p)
        lines.append(f"• {head}" + (f" ({where})" if where else ""))
        if s.get("why"):
            lines.append(f"  {s['why']}")
    lines += [
        "",
        "Watch the map live: https://xyzo.org/",
        "",
        "This video is an automated summary generated by the XYZO news map. "
        "The narration is machine-generated from published headlines; the "
        "reporting is credited to the outlets listed below.",
    ]

    tags = ["XYZO", "news", "world news", "news map", "global news"]
    for s in stories:
        for cat in [s.get("category"), s.get("event_type")]:
            if cat:
                tags.append(str(cat))
    tags.append("automated")

    return {
        "title": title,
        "description": "\n".join(lines)[:5000],
        "tags": list(dict.fromkeys(tags))[:30],
        "category_id": "25",  # News & Politics
        "privacy_status": "public",
        "self_declared_made_for_kids": False,
        "publish_at": None,  # set by --schedule
    }


def build_service(creds: dict[str, str]):
    """An authorised YouTube API client (refresh-token flow)."""
    from google.oauth2.credentials import Credentials
    from googleapiclient.discovery import build

    credentials = Credentials(
        token=None,
        refresh_token=creds["refresh_token"],
        token_uri="https://oauth2.googleapis.com/token",
        client_id=creds["client_id"],
        client_secret=creds["client_secret"],
        scopes=SCOPES,
    )
    return build("youtube", "v3", credentials=credentials, cache_discovery=False)


def upload(video_path: str, meta: dict[str, Any], creds: dict[str, str],
           chunk_mb: int = 16) -> Optional[str]:
    """Resumable upload. Returns the video id."""
    service = build_service(creds)
    body = {
        "snippet": {
            "title": meta["title"],
            "description": meta["description"],
            "tags": meta["tags"],
            "categoryId": meta.get("category_id", "25"),
        },
        "status": {
            "privacyStatus": meta.get("privacy_status", "public"),
            "selfDeclaredMadeForKids": bool(meta.get("self_declared_made_for_kids")),
        },
    }
    if meta.get("publish_at"):
        body["status"]["publishAt"] = meta["publish_at"]

    insert = service.videos().insert(
        part="snippet,status",
        body=body,
        media_body=_MediaFileUpload(video_path, chunksize=chunk_mb * 1024 * 1024, resumable=True),
    )
    response = insert.execute()
    return response.get("id")


try:  # googleapiclient is optional — only needed to actually upload
    from googleapiclient.http import MediaFileUpload as _MediaFileUpload
except Exception:  # noqa: BLE001
    _MediaFileUpload = None  # type: ignore[assignment]


def authorise_flow(creds: dict[str, str]) -> Optional[str]:
    """Interactive OAuth to mint a refresh token (one-off, by hand)."""
    try:
        from google_auth_oauthlib.flow import InstalledAppFlow
    except Exception:
        _log("google-auth-oauthlib is not installed — pip install it to authorise")
        return None
    client_config = {
        "installed": {
            "client_id": creds["client_id"],
            "client_secret": creds["client_secret"],
            "auth_uri": "https://accounts.google.com/o/oauth2/auth",
            "token_uri": "https://oauth2.googleapis.com/token",
            "redirect_uris": ["urn:ietf:wg:oauth:2.0:oob", "http://localhost"],
        }
    }
    flow = InstalledAppFlow.from_client_config(client_config, scopes=SCOPES)
    url, _state = flow.authorization_url(prompt="consent")
    _log("Open this URL, approve, then paste the code here:")
    print(url)
    code = input("code> ").strip()
    flow.fetch_token(code=code)
    rt = flow.credentials.refresh_token
    _log(f"refresh token: {rt}")
    _log("Add it to /etc/xyzo/xyzo.env as YOUTUBE_REFRESH_TOKEN")
    return rt


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Publish the daily digest video")
    ap.add_argument("--video", default=DEFAULT_VIDEO)
    ap.add_argument("--storyboard", default=DEFAULT_STORYBOARD)
    ap.add_argument("--digest", default=DEFAULT_DIGEST)
    ap.add_argument("--dry-run", action="store_true", help="build metadata, upload nothing")
    ap.add_argument("--status", action="store_true", help="print what would be published")
    ap.add_argument("--private", action="store_true", help="upload as unlisted")
    ap.add_argument("--schedule", default=None,
                    help="ISO timestamp to publish at instead of now")
    ap.add_argument("--auth", action="store_true", help="mint a refresh token")
    args = ap.parse_args(argv)

    creds = load_credentials()

    if args.auth:
        if credentials_present(creds) != ["refresh_token"]:
            missing = [k for k in ("client_id", "client_secret") if not creds.get(k)]
            if missing:
                _log(f"set {', '.join(missing)} first")
                return 1
        rt = authorise_flow(creds)
        return 0 if rt else 1

    if not os.path.exists(args.digest):
        _log(f"no digest at {args.digest} — run worker/daily_digest.py first")
        return 1
    with open(args.digest, "r", encoding="utf-8") as fh:
        digest = json.load(fh)
    storyboard = {}
    if os.path.exists(args.storyboard):
        with open(args.storyboard, "r", encoding="utf-8") as fh:
            storyboard = json.load(fh)

    meta = build_metadata(digest, storyboard)
    if args.private:
        meta["privacy_status"] = "unlisted"
    if args.schedule:
        meta["publish_at"] = args.schedule

    print(json.dumps({k: v for k, v in meta.items() if k != "description"}, indent=1))
    print("--- description ---")
    print(meta["description"])

    if args.status or args.dry_run:
        missing = credentials_present(creds)
        if missing:
            _log(f"NO UPLOAD (missing credentials: {', '.join(missing)})")
        else:
            _log("credentials present — run without --dry-run to upload")
        return 0

    missing = credentials_present(creds)
    if missing:
        _log(f"refusing to upload: missing {', '.join(missing)}")
        _log("set YOUTUBE_CLIENT_ID / YOUTUBE_CLIENT_SECRET / YOUTUBE_REFRESH_TOKEN")
        return 1
    if not os.path.exists(args.video):
        _log(f"no video at {args.video} — run worker/digest_render.py first")
        return 1
    if _MediaFileUpload is None:
        _log("googleapiclient is not installed")
        return 1

    _log(f"uploading {args.video} ...")
    try:
        vid = upload(args.video, meta, creds)
    except Exception as exc:  # noqa: BLE001
        _log(f"upload failed: {exc}")
        return 1
    _log(f"uploaded: https://www.youtube.com/watch?v={vid}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
