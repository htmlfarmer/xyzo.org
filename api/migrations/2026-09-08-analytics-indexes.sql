--            (cost=32.88..657.95 rows=1109)
--            ->  Bitmap Index Scan on news_interactions_time_idx
--            Execution Time: 1.93 ms
--     Verdict: ALREADY INDEXED. news_interactions_time_idx (created_at
--              DESC) covers the filter. No new index.
