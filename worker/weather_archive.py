#!/usr/bin/env python3
"""weather_archive.py — keep a YEAR of the weather maps.

WHAT THIS ARCHIVES
------------------
Every GFS analysis cycle (00/06/12/18Z — four a day) the site publishes
three things:

  * the 10 m wind field   (public_html/data/wind/grid-1deg.bin)
  * the 2 m temperature   (public_html/data/temp/grid-1deg.bin)
  * the pressure contours (the weather_isobars table, cut from the 0.25°
    GFS PRMSL analysis)

A reader can therefore ask "what did the weather look like on 3 March
last year?" — and today the answer is "you cannot: the worker replaces
the previous cycle when the next one lands". This worker keeps a copy of
each cycle so the past is a lookup.

WHY THE 1° GRIDS, NOT THE 0.25° ONES
-------------------------------------
The flat map renders the 0.25° grids; the 3D globe renders the 1° ones
("the SAME field, subsampled by the SAME worker run"). The archive takes
the 1° copies, and the numbers are what the year costs:

    wind  1°   260,640 B   ->  ~100 KB gzipped
    temp  1°   130,320 B   ->  ~60 KB gzipped
    isobars (the classic 4 hPa chart, ~1,100 lines) -> ~60 KB gzipped
    ------------------------------------------------------------------
    ~220 KB a cycle x 1,460 cycles (4 a day x 365) = ~320 MB a year

The 0.25° grids would be 6 MB a cycle = 8.8 GB a year, and the 0.05 hPa
isobar set (39,320 rows, 297 MB in PostGIS) would be 350 GB a year. So:
the 1° field and the 4 hPa chart — the classic synoptic map — for a
little over a third of a gigabyte. That is the trade this worker makes,
and the reader is told which resolution they are looking at.

WHAT IS STORED IS A COPY OF A PUBLISHED FILE
--------------------------------------------
The archive does not re-compute anything: it copies the grids the
workers already published and exports the isobar lines the API already
serves. There is no second implementation of the field.

Run:
    python3 -m worker.weather_archive --archive          # archive the current cycle
    python3 -m worker.weather_archive --archive --all    # backfill every cycle still in the table
    python3 -m worker.weather_archive --stats            # how much disk, how many cycles
    python3 -m worker.weather_archive --prune            # drop cycles past the retention
"""
from __future__ import annotations

import argparse
import gzip
import json
import os
import shutil
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from worker.db import connect  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public_html" / "data"

# The archive lives OUTSIDE the web root and OUTSIDE git: it is a
# runtime artefact (like data/nn_models/), regenerated by this worker,
# and it must not bloat the repository.
ARCHIVE_ROOT = Path(os.environ.get("XYZO_WEATHER_ARCHIVE", str(ROOT / "data" / "weather_archive")))

# A little over a year. The user asked for a year; the extra fortnight
# covers a leap year and the cycles that straddle it.
RETENTION_DAYS = int(os.environ.get("XYZO_WEATHER_ARCHIVE_DAYS", "400"))

# The classic synoptic chart: every 4 hPa. The 0.05 hPa lattice the
# worker cuts is 39,320 rows (297 MB) a cycle — a year of THAT is
# 350 GB, and it is not what a reader reads a synoptic chart from.
STEP_HPA = 4.0
STEP_MIN_HPA = 940.0
STEP_MAX_HPA = 1060.0

# The isobar lines are already smoothed; the API simplifies them to the
# viewport's tolerance on the way out. The archive uses one fixed
# tolerance so a stored line is the same shape for every reader.
SIMPLIFY_DEG = 0.05


def log(msg: str) -> None:
    print(f"[weather-archive] {msg}", flush=True)


def step_levels(step: float = STEP_HPA) -> list[float]:
    """The levels of the classic chart — the same rule the API uses."""
    first = int(-(-STEP_MIN_HPA // step))  # ceil
    out = []
    k = first
    while k * step <= STEP_MAX_HPA + step * 1e-9:
        out.append(round(k * step * 100) / 100)
        k += 1
    return out


def cycle_key(iso: str) -> str:
    """2026-11-12T06:00:00Z -> 2026111206."""
    dt = datetime.fromisoformat(iso.replace("Z", "+00:00"))
    return dt.strftime("%Y%m%d%H")


def read_published(field: str) -> tuple[dict, bytes] | None:
    """The published 1° grid and its meta, or None."""
    meta_path = PUBLIC / field / "meta-1deg.json"
    grid_path = PUBLIC / field / "grid-1deg.bin"
    if not meta_path.exists() or not grid_path.exists():
        return None
    meta = json.loads(meta_path.read_text())
    return meta, grid_path.read_bytes()


def current_isobar_cycle() -> str | None:
    """The cycle the isobar table currently holds.

    The three fields are published by THREE workers on their own timers,
    so their cycles can differ by one analysis (measured 2026-11-12: the
    wind grid was the 06:00Z analysis and the isobars the 00:00Z one).
    The archive therefore records each field's own cycle rather than
    pretending they are one.
    """
    try:
        with connect() as conn:
            row = conn.execute(
                """
                SELECT run_time FROM weather_isobars
                WHERE source = 'gfs' ORDER BY run_time DESC LIMIT 1
                """
            ).fetchone()
        if row is None:
            return None
        rt = row["run_time"]
        return rt.isoformat().replace("+00:00", "Z")
    except Exception as e:
        log(f"cannot read the isobar cycle: {e}")
        return None


def export_isobars(run_time: str) -> list[dict] | None:
    """The isobar lines for one cycle, in the API's own item shape."""
    levels = step_levels()
    try:
        with connect() as conn:
            rows = conn.execute(
                """
                SELECT level_hpa,
                       ST_AsGeoJSON(ST_Simplify(geom, %s)) AS gj
                FROM weather_isobars
                WHERE source = 'gfs'
                  AND run_time = %s
                  AND level_hpa = ANY(%s)
                """,
                (SIMPLIFY_DEG, run_time, levels),
            ).fetchall()
    except Exception as e:
        log(f"isobar export failed for {run_time}: {e}")
        return None
    items = []
    for r in rows:
        gj = r["gj"]
        if isinstance(gj, str):
            try:
                gj = json.loads(gj)
            except json.JSONDecodeError:
                continue
        items.append({"level_hpa": float(r["level_hpa"]), "coordinates": (gj or {}).get("coordinates", [])})
    return items


def write_gz(path: Path, data: bytes) -> int:
    """Write gzip-compressed bytes; return the SIZE ON DISK."""
    tmp = path.with_suffix(path.suffix + ".tmp")
    with gzip.open(tmp, "wb", compresslevel=6) as fh:
        fh.write(data)
    tmp.replace(path)
    return path.stat().st_size


def archive_cycle(cycle_iso: str, force: bool = False) -> dict | None:
    """Archive one cycle. Returns a summary, or None if there was nothing to do."""
    key = cycle_key(cycle_iso)
    out_dir = ARCHIVE_ROOT / key
    if out_dir.exists() and not force:
        return None

    wind = read_published("wind")
    temp = read_published("temp")
    if not wind or not temp:
        log(f"no published 1° grids yet (wind/temp missing) — nothing to archive")
        return None
    w_meta, w_grid = wind
    t_meta, t_grid = temp

    out_dir.mkdir(parents=True, exist_ok=True)
    sizes = {
        "wind": write_gz(out_dir / "wind.bin.gz", w_grid),
        "temp": write_gz(out_dir / "temp.bin.gz", t_grid),
    }

    # The isobars carry their OWN cycle (the three fields are published by
    # three workers on three timers, and their analyses can differ by
    # one). Archiving the current table is right — it is the cycle the
    # site is drawing — and the meta records which one it was.
    isobar_cycle = current_isobar_cycle() or cycle_iso
    items = export_isobars(isobar_cycle) or []
    if not items:
        log(f"WARNING: no isobar lines for cycle {isobar_cycle} — the archive "
            f"entry has pressure but no chart")
    sizes["isobars"] = write_gz(
        out_dir / "isobars.json.gz",
        json.dumps({"items": items, "source": "gfs", "run_time": isobar_cycle}).encode(),
    )

    meta = {
        "cycle": cycle_iso,
        "key": key,
        "archived_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "resolution": "1deg",
        "step_hpa": STEP_HPA,
        "wind": {
            "meta": w_meta,
            "bytes": sizes["wind"],
            "cols": w_meta.get("grid", {}).get("cols"),
            "rows": w_meta.get("grid", {}).get("rows"),
        },
        "temp": {
            "meta": t_meta,
            "bytes": sizes["temp"],
            "cols": t_meta.get("grid", {}).get("cols"),
            "rows": t_meta.get("grid", {}).get("rows"),
        },
        "isobars": {
            "bytes": sizes["isobars"],
            "lines": len(items),
            "cycle": isobar_cycle,
            "levels": sorted({i["level_hpa"] for i in items}),
        },
        "total_bytes": sum(sizes.values()),
    }
    (out_dir / "meta.json").write_text(json.dumps(meta, indent=1))
    log(f"archived {cycle_iso}: {meta['total_bytes'] / 1024:.0f} KB "
        f"(wind {sizes['wind'] / 1024:.0f} KB, temp {sizes['temp'] / 1024:.0f} KB, "
        f"isobars {sizes['isobars'] / 1024:.0f} KB, {len(items)} lines)")
    return meta


def write_index() -> dict:
    """The list of archived cycles — what the API serves to the reader."""
    cycles = []
    if ARCHIVE_ROOT.exists():
        for d in sorted(ARCHIVE_ROOT.iterdir()):
            meta_path = d / "meta.json"
            if not d.is_dir() or not meta_path.exists():
                continue
            try:
                m = json.loads(meta_path.read_text())
            except json.JSONDecodeError:
                continue
            cycles.append(
                {
                    "cycle": m.get("cycle"),
                    "key": m.get("key"),
                    "total_bytes": m.get("total_bytes", 0),
                    "lines": m.get("isobars", {}).get("lines", 0),
                }
            )
    index = {"cycles": cycles, "updated_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")}
    ARCHIVE_ROOT.mkdir(parents=True, exist_ok=True)
    tmp = ARCHIVE_ROOT / "index.json.tmp"
    tmp.write_text(json.dumps(index, indent=1))
    tmp.replace(ARCHIVE_ROOT / "index.json")
    return index


def current_cycle() -> str | None:
    """The cycle the site is publishing right now."""
    for field in ("wind", "temp"):
        meta_path = PUBLIC / field / "meta-1deg.json"
        if meta_path.exists():
            try:
                return json.loads(meta_path.read_text()).get("run_time")
            except json.JSONDecodeError:
                continue
    return None


def archive_all() -> dict:
    """Every cycle still in the isobar table (a backfill after the fact)."""
    try:
        with connect() as conn:
            rows = conn.execute(
                """
                SELECT DISTINCT run_time FROM weather_isobars
                WHERE source = 'gfs' ORDER BY run_time
                """
            ).fetchall()
    except Exception as e:
        log(f"cannot list the cycles: {e}")
        return {"archived": 0}
    n = 0
    for r in rows:
        rt = r["run_time"]
        iso = rt.isoformat().replace("+00:00", "Z")
        if archive_cycle(iso):
            n += 1
    write_index()
    return {"archived": n, "candidates": len(rows)}


def prune() -> dict:
    """Drop the cycles past the retention."""
    cutoff = datetime.now(timezone.utc) - timedelta(days=RETENTION_DAYS)
    removed = 0
    if ARCHIVE_ROOT.exists():
        for d in sorted(ARCHIVE_ROOT.iterdir()):
            if not d.is_dir():
                continue
            meta_path = d / "meta.json"
            if not meta_path.exists():
                continue
            try:
                m = json.loads(meta_path.read_text())
                dt = datetime.fromisoformat(str(m.get("cycle", "")).replace("Z", "+00:00"))
            except Exception:
                continue
            if dt < cutoff:
                shutil.rmtree(d, ignore_errors=True)
                removed += 1
    write_index()
    log(f"pruned {removed} cycles older than {RETENTION_DAYS} days")
    return {"removed": removed}


def stats() -> dict:
    index = write_index()
    total = 0
    for d in ARCHIVE_ROOT.iterdir() if ARCHIVE_ROOT.exists() else []:
        if d.is_dir():
            for f in d.iterdir():
                total += f.stat().st_size
    cycles = index["cycles"]
    avg = (total / len(cycles)) if cycles else 0
    per_year = avg * 4 * 365
    return {
        "archive_root": str(ARCHIVE_ROOT),
        "cycles": len(cycles),
        "total_bytes": total,
        "total_mb": round(total / 1e6, 1),
        "avg_cycle_kb": round(avg / 1024, 1),
        "projected_year_mb": round(per_year / 1e6, 1),
        "retention_days": RETENTION_DAYS,
        "oldest": cycles[0]["cycle"] if cycles else None,
        "newest": cycles[-1]["cycle"] if cycles else None,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--archive", action="store_true", help="archive the current cycle")
    ap.add_argument("--all", action="store_true", help="backfill every cycle in the isobar table")
    ap.add_argument("--stats", action="store_true", help="print the archive statistics")
    ap.add_argument("--prune", action="store_true", help="drop cycles past the retention")
    ap.add_argument("--force", action="store_true", help="re-archive a cycle that is already stored")
    args = ap.parse_args()

    if args.stats:
        print(json.dumps(stats(), indent=2))
        return 0
    if args.prune:
        print(json.dumps(prune(), indent=2))
        return 0
    if args.all:
        print(json.dumps(archive_all(), indent=2))
        return 0
    if args.archive:
        cycle = current_cycle()
        if not cycle:
            log("no published cycle to archive")
            return 1
        done = archive_cycle(cycle, force=args.force)
        write_index()
        if done is None:
            log(f"{cycle} is already archived")
            return 0
        return 0
    ap.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
